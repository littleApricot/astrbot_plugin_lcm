const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE_PATH||undefined});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},timezoneId:'America/Los_Angeles'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:6197');
  const view=page.frame({name:'viewer'});assert.ok(view);
  await view.getByRole('button',{name:/QQ 讨论群/}).click();
  await view.locator('#stream .card').first().waitFor();
  assert.match(await view.locator('#notice').innerText(),/下一轮/);
  assert.match(await view.locator('#session-name').innerText(),/Asia\/Shanghai/);
  assert.match(await view.evaluate(()=>date(1792663200)),/18:00:00/);
  assert.equal(await view.evaluate(()=>filterTime('2026-10-22T18:00')),'2026-10-22T10:00:00.000Z');
  await page.screenshot({path:process.cwd()+'/preview-light.png',fullPage:false});
  const summary=view.locator('#stream .summary').first();assert.ok(await summary.count());
  await summary.getByRole('button',{name:'逐层查看来源'}).click();
  await view.locator('#source .card').first().waitFor();
  await view.waitForFunction(()=>document.querySelectorAll('#source .card').length>=2);
  assert.match(await view.locator('#source .card').first().innerText(),/L2/);
  await view.locator('#source .summary').nth(1).getByRole('button',{name:'逐层查看来源'}).click();
  await view.waitForFunction(()=>document.querySelectorAll('#breadcrumbs button').length===2);
  await view.waitForFunction(()=>document.querySelectorAll('#source .card').length===3);
  assert.match(await view.locator('#source .card').first().innerText(),/L1/);
  await view.locator('#breadcrumbs button').first().click();
  await view.waitForFunction(()=>document.querySelectorAll('#breadcrumbs button').length===1);
  await view.getByRole('button',{name:'查看原始完整轮次',exact:true}).click();
  await view.locator('#source .source-label').first().waitFor();
  assert.match(await view.locator('#source').innerText(),/完整|原始|工具/);
  await view.locator('#close-inspector').click();
  await view.locator('[data-mode=history]').click();
  await view.locator('#query').fill('查看器');
  await view.locator('#search-form button[type=submit]').click();
  await view.locator('#stream mark').first().waitFor();
  assert.ok(await view.locator('#stream mark').count()>0);
  await view.locator('#stream .card-foot button').first().click();
  await view.locator('#source .card').first().waitFor();
  await view.locator('#close-inspector').click();
  await view.locator('[data-mode=request]').click();
  await view.locator('#step option').first().waitFor({state:'attached'});
  await view.waitForFunction(()=>document.querySelector('#stream').textContent.includes('当前记忆'));
  assert.match(await view.locator('#notice').innerText(),/实际交给/);
  await view.locator('[data-mode=context]').click();
  await view.locator('#stream .summary').first().getByRole('button',{name:'逐层查看来源'}).click();
  await view.locator('#source .card').first().waitFor();
  await view.locator('#theme').click();assert.equal(await view.locator('html').getAttribute('data-theme'),'dark');
  await page.screenshot({path:process.cwd()+'/preview-dark.png',fullPage:false});
  await view.locator('#close-inspector').click();
  await page.setViewportSize({width:390,height:844});
  await view.locator('#nav').click();assert.ok(await view.locator('#sidebar').evaluate(e=>e.classList.contains('open')));
  await view.locator('#close-nav').click();
  console.log('mobile-overflow',await view.evaluate(()=>({w:innerWidth,scroll:document.documentElement.scrollWidth,wide:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1).slice(0,10).map(e=>[e.tagName,e.className,e.id,Math.round(e.getBoundingClientRect().width)])})));
  assert.equal(await view.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:process.cwd()+'/preview-mobile.png',fullPage:false});
  assert.deepEqual(errors,[]);
  console.log('PASS: context/history/request tabs, source expansion, keyword highlighting, complete-round lookup, dark mode, narrow-screen navigation; no page errors');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
